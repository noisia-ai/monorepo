#!/usr/bin/env bash
set -euo pipefail

if [[ "${GITHUB_ACTIONS:-}" != "true" ]]; then
  echo "R16 CI benchmark may run only on a fresh GitHub Actions runner." >&2
  exit 2
fi

repo_root="$(git rev-parse --show-toplevel)"
export R16BENCH_RUN_ID="benchmark-pg17"
export R16BENCH_SERVICES="postgres,redis"
lab_dir="$repo_root/.data/piloto-masivo/r16/labs/$R16BENCH_RUN_ID"
if [[ -e "$lab_dir" || -L "$lab_dir" ]]; then
  echo "R16 CI benchmark metadata already exists; refusing to reuse it." >&2
  exit 2
fi

project="r16bench-$R16BENCH_RUN_ID"
fixed_container="r16-benchmark-pg17"
fixed_redis_container="${project}-redis-1"
fixed_volume="r16bench-benchmark-pg17_postgres-data"
fixed_network="${project}_default"

# A query error is not evidence that a resource is absent. Keep all discovery
# before lab-up and before registering cleanup, so pre-existing data is never
# removed by this job.
if ! docker info >/dev/null 2>&1; then
  echo "Docker daemon is unavailable; refusing to start the R16 CI benchmark." >&2
  exit 2
fi

if ! project_containers="$(docker ps --all --filter "label=com.docker.compose.project=$project" --format '{{.ID}}')" \
  || ! all_container_names="$(docker ps --all --format '{{.Names}}')" \
  || ! project_volumes="$(docker volume ls --filter "label=com.docker.compose.project=$project" --format '{{.Name}}')" \
  || ! all_volume_names="$(docker volume ls --format '{{.Name}}')" \
  || ! project_networks="$(docker network ls --filter "label=com.docker.compose.project=$project" --format '{{.Name}}')" \
  || ! all_network_names="$(docker network ls --format '{{.Name}}')"; then
  echo "Docker resource discovery failed; refusing to assume the R16 project is fresh." >&2
  exit 2
fi

if [[ -n "$project_containers" || -n "$project_volumes" || -n "$project_networks" ]] \
  || [[ $'\n'$all_container_names$'\n' == *$'\n'$fixed_container$'\n'* ]] \
  || [[ $'\n'$all_container_names$'\n' == *$'\n'$fixed_redis_container$'\n'* ]] \
  || [[ $'\n'$all_volume_names$'\n' == *$'\n'$fixed_volume$'\n'* ]] \
  || [[ $'\n'$all_network_names$'\n' == *$'\n'$fixed_network$'\n'* ]]; then
  echo "R16 CI benchmark resources already exist; refusing to reuse or remove them." >&2
  exit 2
fi

cleanup() {
  local status=$?
  trap - EXIT
  if [[ -f "$lab_dir/private.env" ]]; then
    R16BENCH_RUN_ID="$R16BENCH_RUN_ID" "$repo_root/scripts/r16/lab-down.sh" || {
      local cleanup_status=$?
      if (( status == 0 )); then status=$cleanup_status; fi
    }
  fi
  exit "$status"
}
trap cleanup EXIT

"$repo_root/scripts/r16/lab-up.sh"
lab_dir="$repo_root/.data/piloto-masivo/r16/labs/$R16BENCH_RUN_ID"

set -a
# The file is generated by this script's own loopback-only lab-up step.
# shellcheck disable=SC1091
source "$lab_dir/connection.env"
set +a
export NOISIA_R16_LOCAL_PG_LAB="r16-benchmark-pg17"
export DATABASE_SSL="false"
export NOISIA_DB_SMOKE_ALLOW_REMOTE="false"
export NOISIA_DB_SMOKE_RESET_SCHEMA="true"
export NOISIA_DB_SMOKE_EMULATE_SUPABASE_ROLES="true"
export NOISIA_R16_LOCAL_PG_LAB="r16-benchmark-pg17"
export NOISIA_R16_NATIVE_FIXTURE_PG="true"
export NOISIA_R16_UNSENT_PG="true"
export NOISIA_R16_RAW_PAGE_LOCKS_PG="true"

corepack pnpm --filter @noisia/db db:smoke:migrations
corepack pnpm exec tsx --test infrastructure/db/migrations/signal-client-workspace-entry.batch-equivalence.postgres.test.ts
corepack pnpm exec tsx --test infrastructure/db/migrations/signal-client-workspace-entry.preparation-page-equivalence.postgres.test.ts
corepack pnpm exec tsx --test infrastructure/db/migrations/signal-r16-native-fixture.postgres.test.ts
corepack pnpm exec tsx --test infrastructure/db/migrations/signal-labeling-unsent.postgres.test.ts
corepack pnpm exec tsx --test infrastructure/db/migrations/signal-labeling-raw-page-locks.postgres.test.ts
export NOISIA_R16_IMPORT_INVALIDATION_PG="true"
export NOISIA_R16_INPUT_BOUNDS_PG="true"
corepack pnpm exec tsx --test \
  infrastructure/db/migrations/signal-semantic-review-attribution-lookup.postgres.test.ts \
  infrastructure/db/migrations/signal-mass-labeling-input-bounds.postgres.test.ts | tee r16-h1-native-guards.tap
if ! grep -qx '# skipped 0' r16-h1-native-guards.tap; then
  echo '::error::R16 import or bounded-input PostgreSQL tests were skipped'
  exit 1
fi
corepack pnpm exec tsx --test services/workers/src/providers/jev-account-rate-limit.redis.test.ts
corepack pnpm exec tsx --test scripts/r16/*.test.ts
# The R16 product contract is Listening (base plus consumer-scoped topics),
# not the superseded Mass V2 projection benchmark. Native legacy guards above
# remain covered; this final stage uses the unchanged full acceptance workload.
export NOISIA_SIGNAL_LISTENING_ENABLED="true"
export NOISIA_JEV_PROVIDER_ENABLED="true"
export NOISIA_JEV_STREAMING_V2_ENABLED="true"
corepack pnpm exec tsx scripts/r16/run-listening-ci.ts
