#!/usr/bin/env bash
set -euo pipefail

if [[ "${GITHUB_ACTIONS:-}" != "true" ]]; then
  echo 'R16 calibration requires its real CI job' >&2
  exit 1
fi
if docker inspect r16-benchmark-pg17 >/dev/null 2>&1; then
  echo 'R16 calibration requires a fresh independent lab' >&2
  exit 1
fi
if docker volume inspect r16bench-benchmark-pg17_postgres-data >/dev/null 2>&1; then
  echo 'R16 calibration refuses a pre-existing database volume' >&2
  exit 1
fi

repo_root="$(git rev-parse --show-toplevel)"
export R16BENCH_RUN_ID="benchmark-pg17"
export R16BENCH_SERVICES="postgres,redis"
"$repo_root/scripts/r16/lab-up.sh"
cleanup() { "$repo_root/scripts/r16/lab-down.sh"; }
trap cleanup EXIT
set -a
# Generated by this job's own loopback-only lab; never a shared credentials file.
# shellcheck disable=SC1091
source "$repo_root/.data/piloto-masivo/r16/labs/$R16BENCH_RUN_ID/connection.env"
set +a
export NOISIA_R16_LOCAL_PG_LAB="r16-benchmark-pg17"
export DATABASE_SSL="false"
export NOISIA_DB_SMOKE_ALLOW_REMOTE="false"
# The official Supabase-role emulation requires disposable-schema mode. The
# fresh-container AND fresh-volume guards above exclude any retained database.
export NOISIA_DB_SMOKE_RESET_SCHEMA="true"
export NOISIA_DB_SMOKE_EMULATE_SUPABASE_ROLES="true"
export NOISIA_R16_NATIVE_FIXTURE_PG="true"
export NOISIA_R16_LISTENING_CALIBRATION_SCALE_PG="true"
corepack pnpm --filter @noisia/db db:smoke:migrations
corepack pnpm exec tsx --test infrastructure/db/migrations/signal-listening-calibration.postgres.test.ts | tee r16-calibration-pg.tap
if ! grep -qx '# skipped 0' r16-calibration-pg.tap; then
  echo '::error::R16 calibration PostgreSQL test was skipped'
  exit 1
fi
